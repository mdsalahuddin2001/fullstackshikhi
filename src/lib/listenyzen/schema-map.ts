export interface Relation {
  from: string;
  to: string;
  field: string;
  /** `ref`: single id; `many`: id array; `poly`: id whose target depends on another field. */
  kind: 'ref' | 'many' | 'poly';
  /** Tenant / brand scoping copy (companyId, or a denormalized brandId). */
  scope: boolean;
}

const isScope = (model: Model, field: Field): boolean =>
  field.n === 'companyId' || (field.n === 'brandId' && Boolean(field.denorm)) || (field.n === 'brandId' && model.domain === 'rollups');

export const RELATIONS: Relation[] = MODELS.flatMap(model =>
  model.fields.flatMap((field): Relation[] => {
    if (field.ref) {
      return [{ from: model.name, to: field.ref, field: field.n, kind: field.t.endsWith('[]') ? 'many' : 'ref', scope: isScope(model, field) }];
    }
    return (field.poly ?? []).map(to => ({ from: model.name, to, field: field.n, kind: 'poly' as const, scope: false }));
  })
);

export const modelByName = (name: string): Model | undefined => MODELS.find(m => m.name === name);
