export interface Field {
  /** Path; `a.b` is inside an embedded object, `a[].b` inside an embedded array. */
  n: string;
  /** Declared type, TypeScript-style. */
  t: string;
  req?: boolean;
  def?: string;
  /** `ref:` target model. */
  ref?: string;
  /** Polymorphic id: which models it can point at (no Mongoose `ref`). */
  poly?: string[];
  /** Copied from another record for scoping or display, not the source of truth. */
  denorm?: boolean;
  /** `select: false`: left out of reads unless asked for. */
  hidden?: boolean;
  immutable?: boolean;
  unique?: boolean;
  note?: string;
}

export interface Model {
  name: string;
  collection: string;
  domain: Domain;
  file: string;
  /** How createdAt / updatedAt are kept. */
  time: 'baseSchema' | 'timestamps' | 'createdAt' | 'none';
  summary: string;
  fields: Field[];
  /** Indexes in declaration order; `!` = unique, `partial`/`sparse`/`TTL` noted. */
  indexes: string[];
  /** Discriminator models stored in the same collection. */
  variants?: { name: string; key: string; value: string }[];
}

